// Helper to append an audit log entry from any controller
export const recordAuditLog = ({ action, user, targetType, targetId, details }) => {
  const entry = {
    _id: 'aud_' + Date.now() + '_' + Math.floor(Math.random() * 1000),
    action,
    performedBy: user?.email || 'system@nexus.io',
    performerRole: user?.role || 'system',
    targetType,
    targetId: String(targetId || 'N/A'),
    details,
    ipAddress: '127.0.0.1',
    timestamp: new Date().toISOString(),
  };
  memoryStore.auditLogs.unshift(entry);
  if (memoryStore.auditLogs.length > 200) {
    memoryStore.auditLogs.pop();
  }
  return entry;
};
